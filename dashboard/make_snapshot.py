"""Build the self-contained dashboard snapshot pages (desktop + phone) for claude.ai Artifacts.

WHAT THIS MAKES: two single-file HTML pages that embed real store data and run the full
Mission Control UI with NO server - the fetch layer is shimmed to serve embedded JSON.
Published as claude.ai Artifacts they give Greg cruise-able private links; the standing
URLs + refresh procedure live in DASHBOARD_HANDOFF_S100.md (S100.1 addendum).

USAGE (server must be running with the stores pulled - see README.md):
    python -m uvicorn dashboard.server:app --port 8100 &
    python dashboard/make_snapshot.py --out-dir /path/to/scratch [--days 20260122,20260130]

Outputs: davisai-dash-snapshot.html (desktop; viewport width=1130 so a rotated phone
auto-fits it) and davisai-dash-snapshot-phone.html (portrait phone: bottom-tab nav,
single column). Blind-run hygiene: default day list contains NO Feb 2026 days - G12/G13
have not run blind; a guard refuses to embed the un-walked window.
"""
from __future__ import annotations

import argparse
import json
import os
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
FRONTEND = os.path.join(HERE, "frontend")
DEFAULT_DAYS = ["20251223", "20260107", "20260120", "20260122", "20260130", "20260717"]
DEFAULT_TAPE_DAYS = ["20260122"]


def collect_embed(base: str, days: list[str], tape_days: list[str]) -> dict:
    def get(p):
        with urllib.request.urlopen(base + p, timeout=300) as r:
            return json.load(r)

    snapshots = {d: get(f"/desk/snapshot?day={d}") for d in days}
    anchor = snapshots[days[0]]
    shared = {k: anchor[k] for k in ("health", "brain", "lag_map", "doctrine_banner")}
    return {
        "default_day": tape_days[0] if tape_days else days[0],
        "days": days,
        "shared": shared,
        "per_day": {d: {"decision_state": s["decision_state"],
                        "generated_at_utc": s["generated_at_utc"]} for d, s in snapshots.items()},
        "lag_window_atm": get("/lag-map/window?band=ATM"),
        "kalshi_days": get("/kalshi/days"),
        "nymex_bars": {d: get(f"/nymex/minute-bars/{d}") for d in tape_days},
    }


SHIM = """
window.__DAVISAI_EMBED__ = __EMBED_JSON__;
(() => {
  const E = window.__DAVISAI_EMBED__;
  const json = (obj, status = 200) =>
    Promise.resolve(new Response(JSON.stringify(obj), { status, headers: { "Content-Type": "application/json" } }));
  const assemble = day => {
    const pd = E.per_day[day];
    if (!pd) return { as_of_day: day, generated_at_utc: null, ...E.shared,
      decision_state: { available: false, day, error: "day not embedded in this static snapshot - embedded days: " + E.days.join(", ") } };
    return { as_of_day: day, generated_at_utc: pd.generated_at_utc, ...E.shared, decision_state: pd.decision_state };
  };
  const orig = window.fetch.bind(window);
  window.fetch = (url, ...rest) => {
    const u = String(url);
    if (!u.startsWith("/api/v1")) return orig(url, ...rest);
    const [path, qs] = u.slice("/api/v1".length).split("?");
    const params = new URLSearchParams(qs || "");
    if (path === "/desk/snapshot") return json(assemble(params.get("day") || E.default_day));
    if (path === "/lag-map/window") return json(E.lag_window_atm);
    if (path === "/kalshi/days") return json(E.kalshi_days);
    const mBars = path.match(/^\\/nymex\\/minute-bars\\/(\\d{8})$/);
    if (mBars) return json(E.nymex_bars[mBars[1]] ||
      { available: false, day: mBars[1], reason: "tape not embedded in this static snapshot" });
    return json({ available: false, reason: "endpoint not embedded in this static snapshot" }, 404);
  };
})();
"""

