def banner(phone: bool, days: list[str], tape_days: list[str]) -> str:
    tag = "phone build" if phone else "for note-taking"
    day_list = ", ".join(f"{d[4:6]}-{d[6:]}" + (" (default, real NYMEX tape)" if d in tape_days else "")
                         for d in days)
    return f"""
  <div style="background:#1a2438;border-bottom:1px solid rgba(127,224,167,.25);color:#c8d4e8;
              font:{'10' if phone else '12'}px/1.5 ui-monospace,monospace;padding:7px 12px;letter-spacing:.02em">
    STATIC SNAPSHOT ({tag}) - not the live server. Real stores captured at build time.
    Embedded as-of days: {day_list}. Other dates show an honest not-embedded notice.
    Feb 2026 deliberately excluded (blind-run hygiene, G12/G13 not yet walked).
  </div>
"""


def build(embed: dict, phone: bool) -> str:
    html = open(os.path.join(FRONTEND, "index.html")).read()
    css = open(os.path.join(FRONTEND, "styles.css")).read()
    appjs = open(os.path.join(FRONTEND, "app.js")).read()
    adapterjs = open(os.path.join(FRONTEND, "adapter.js")).read()
    body = html.split("<body>", 1)[1].rsplit("</body>", 1)[0]
    body = body.replace('<script src="app.js"></script>', "").replace('<script src="adapter.js"></script>', "")
    viewport = ('<meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover" />'
                if phone else '<meta name="viewport" content="width=1130" />')
    title = "DavisAI Mission Control - " + ("phone snapshot" if phone else "snapshot")
    shim = SHIM.replace("__EMBED_JSON__", json.dumps(embed))
    return f"""<title>{title}</title>
{viewport}
<style>{css}
{PHONE_CSS if phone else ''}</style>
{banner(phone, embed['days'], list(embed['nymex_bars']))}
{body}
<script>
{shim}
{appjs}
{adapterjs}
</script>
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="http://127.0.0.1:8100/api/v1")
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--days", default=",".join(DEFAULT_DAYS))
    ap.add_argument("--tape-days", default=",".join(DEFAULT_TAPE_DAYS),
                    help="days whose NYMEX minute bars embed (must be local; large)")
    a = ap.parse_args()
    days = a.days.split(",")
    tape_days = [d for d in a.tape_days.split(",") if d]
    feb = [d for d in days + tape_days if d.startswith("202602")]
    if feb:
        raise SystemExit(f"blind-run hygiene: refuse to embed un-walked Feb 2026 days {feb} "
                         "(remove them, or update this guard only after G12/G13 walk)")
    embed = collect_embed(a.base, days, tape_days)
    os.makedirs(a.out_dir, exist_ok=True)
    for phone, name in ((False, "davisai-dash-snapshot.html"), (True, "davisai-dash-snapshot-phone.html")):
        out = os.path.join(a.out_dir, name)
        open(out, "w").write(build(embed, phone))
        print(f"[make_snapshot] {out}: {os.path.getsize(out)/1e6:.2f} MB")
    print("[make_snapshot] publish via the Artifact tool; republishing the same file path from "
          "the SAME conversation keeps the URL - from a new session pass the existing artifact "
          "URL (see the S100.1 addendum in DASHBOARD_HANDOFF_S100.md)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
