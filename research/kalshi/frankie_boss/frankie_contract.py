class FrankieProjector:
    """Projects internal head outputs into BLD-1.

    The internal head names are deliberately NOT hardcoded here beyond
    the ones the projection consumes. Add a head, and it stays internal
    until you decide how it maps to a BLD-1 field. Silent passthrough of
    a new internal quantity into Frankie's contract is exactly the kind
    of seam erosion the adapter exists to prevent.
    """

    def __init__(
        self,
        specialist: str,
        group: str,
        confidence_floor: float | None = None,
        calibrator_version: str = "identity/1",
    ):
        if confidence_floor is not None:
            raise ValueError(
                "numeric confidence floors are not part of BLD-1; "
                "project an already-governed low|med|high label"
            )
        self.specialist = specialist
        self.group = group
        self.calibrator_version = calibrator_version

    def _check_context(self, date: str) -> str:
        for f in BLD1_FIELDS:
            if f.name == "date":
                try:
                    return f.validate(date)
                except ContractError as exc:
                    raise CallerError(str(exc)) from None
        raise AssertionError("date field missing from BLD1_FIELDS")

    def abstain(
        self,
        date: str,
        reasons: Sequence[str],
        packet_hash: str,
        model_version: str,
        reasoning: str = "",
    ) -> BLDRecord:
        """A complete safety abstention when no usable forecast exists."""
        date = self._check_context(date)
        safe_reasoning = reasoning.strip() or "; ".join(reasons) or "No call."
        payload: dict[str, Any] = {
            "specialist": self.specialist,
            "group": self.group,
            "date": date,
            "disposition": Disposition.ABSTAIN.value,
            "reasoning": safe_reasoning,
            "state_defects_and_gaps_reported": list(reasons),
        }
        for f in BLD1_FIELDS:
            if f.name not in payload:
                payload[f.name] = (
                    list(f.zero_on_abstain)
                    if isinstance(f.zero_on_abstain, list)
                    else f.zero_on_abstain
                )
        return BLDRecord(
            payload=validate_bld1(payload),
            packet_hash=packet_hash,
            model_version=model_version,
            calibrator_version=self.calibrator_version,
        )

    def project(
        self,
        date: str,
        heads: Mapping[str, Any],
        packet_hash: str,
        model_version: str,
        packet_defects: Sequence[str] = (),
        reasoning: str = "",
        plays_fired: Sequence[str] = (),
        plays_stood_down: Sequence[str] = (),
        disposition: Disposition | str = Disposition.CALL,
    ) -> BLDRecord:
        """Never raises on bad head output -- returns an ABSTAIN record.

        Packet defects abstain before anything is projected: a degraded
        packet cannot produce a call, and the defect list is what
        state_defects_and_gaps_reported exists to carry.
        """
        date = self._check_context(date)
        if packet_defects:
            return self.abstain(
                date, list(packet_defects), packet_hash, model_version, reasoning
            )

        try:
            payload = {
                "specialist": self.specialist,
                "group": self.group,
                "date": date,
                "guessed_net_usd": heads["guessed_net_usd"],
                "overnight_gap_usd": heads["overnight_gap_usd"],
                "path_p50_curve": heads["path_p50_curve"],
                "reasoning": reasoning,
                "plays_fired": list(plays_fired),
                "plays_stood_down": list(plays_stood_down),
                "confidence": heads["confidence"],
                "state_defects_and_gaps_reported": [],
                "disposition": disposition,
            }
            checked = validate_bld1(payload)
        except ContractError as exc:
            return self.abstain(
                date, [f"contract_violation: {exc}"], packet_hash, model_version, reasoning
            )
        except (KeyError, TypeError, ValueError) as exc:
            return self.abstain(
                date,
                [f"head_output_malformed: {type(exc).__name__}: {exc}"],
                packet_hash,
                model_version,
                reasoning,
            )

        return BLDRecord(
            payload=checked,
            packet_hash=packet_hash,
            model_version=model_version,
            calibrator_version=self.calibrator_version,
        )

    def project_internal(
        self,
        date: str,
        heads: InternalBLD1Heads,
        packet_hash: str,
        model_version: str,
        packet_defects: Sequence[str] = (),
        reasoning: str = "",
        plays_fired: Sequence[str] = (),
        plays_stood_down: Sequence[str] = (),
        disposition: Disposition | str = Disposition.CALL,
    ) -> BLDRecord:
        """Project only the four deliberately mapped learned quantities.

        This typed entry point adds the semantic close-to-close/gap/path check
        before delegating to the same total BLD-1 validator and safety boundary.
        """
        date = self._check_context(date)
        if packet_defects:
            return self.abstain(
                date, list(packet_defects), packet_hash, model_version, reasoning
            )
        if not isinstance(heads, InternalBLD1Heads):
            return self.abstain(
                date,
                ["head_output_malformed: expected InternalBLD1Heads"],
                packet_hash,
                model_version,
                reasoning,
            )

        mapped = heads.bld1_projection()
        try:
            net = float(mapped["guessed_net_usd"])
            gap = float(mapped["overnight_gap_usd"])
            curve = mapped["path_p50_curve"]
            if not isinstance(curve, (list, tuple)) or not curve:
                raise ValueError("path_p50_curve must be a non-empty sequence")
            if not isinstance(curve[-1], (list, tuple)) or len(curve[-1]) != 2:
                raise ValueError(
                    "path_p50_curve points must be [et_time, cumulative_usd]"
                )
            terminal = float(curve[-1][1])
            expected_terminal = net - gap
            if not math.isclose(
                terminal, expected_terminal, rel_tol=0.0, abs_tol=1.0
            ):
                raise ValueError(
                    "path_p50_curve endpoint "
                    f"{terminal} != guessed_net_usd - overnight_gap_usd "
                    f"({expected_terminal})"
                )
        except (TypeError, ValueError, OverflowError) as exc:
            return self.abstain(
                date,
                [f"head_output_malformed: {exc}"],
                packet_hash,
                model_version,
                reasoning,
            )

        return self.project(
            date=date,
            heads=mapped,
            packet_hash=packet_hash,
            model_version=model_version,
            reasoning=reasoning,
            plays_fired=plays_fired,
            plays_stood_down=plays_stood_down,
            disposition=disposition,
        )
