"""Render the DATED classification addendum to the 2026-08-24 source-file inventory.

FRANKIE_WIRING_TODO_S120 item 12: every section of the inventory classified KEEP / CODE /
SUPERSEDED / SEALED / OBSOLETE, each path with its reason, "applied as a DATED addendum to
the inventory, never a silent rewrite". The 2026-08-24 document is a RECORD and is not
touched; this writes `..._ADDENDUM_20260902.md` beside it.

The addendum is a RENDER of `native_knowledge_delivery.classify_inventory`, never prose typed
by hand: the rules live in one place, the table is what a reader sees, and the test suite
holds the committed file byte-identical to the render. `--check` is the gate (exit 1 on
drift), `--write` regenerates. Same shape as `store.py check` / `check --write`.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from research.kalshi.frankie_raw_mbo_benchmark.native_knowledge_delivery import (
    ADDENDUM_PATH,
    BRAIN_PATH,
    CLASSIFICATIONS,
    FEED_INVENTORY_PATH,
    KEEP,
    REPO_ROOT,
    SOURCE_INVENTORY_PATH,
    ClassifiedPath,
    classify_inventory,
)

ADDENDUM_DATE = "2026-09-02"

CLASSIFICATION_MEANING = {
    "KEEP": "knowledge he receives, bound to a registry knowledge layer and receipted by sha256",
    "CODE": "runtime, replay, receipt, test or PROVISIONAL_SHADOW component: not knowledge",
    "SUPERSEDED": "Sol-era / four-helper-era handoff or review (D54, D63, D64, D70)",
    "SEALED": "SEALED_TARGET_ANSWER: October Step-1 answer material, never delivered",
    "OBSOLETE": "obsolete transport bridge, canary record, or the forbidden substitute",
}


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _path_cell(row: ClassifiedPath) -> str:
    if row.path is not None:
        return f"`{row.path}`"
    return f"(no repository path) {_cell(row.bullet)}"


def render_addendum(repo_root: Path | str = REPO_ROOT) -> str:
    rows = classify_inventory(repo_root)
    counts = {c: sum(1 for r in rows if r.classification == c) for c in CLASSIFICATIONS}
    with_path = sum(1 for r in rows if r.path is not None)
    missing = [r.path for r in rows if r.path is not None and not r.exists]
    lines: list[str] = [
        "# NG Exhaustion Frankie Source File Inventory - Classification Addendum",
        "",
        f"Date: {ADDENDUM_DATE}",
        f"Applies to: `{SOURCE_INVENTORY_PATH}` (dated 2026-08-24; a record, never rewritten)",
        f"Companion: `{FEED_INVENTORY_PATH}`",
        "",
        "Generated by `python3 -m research.kalshi.frankie_raw_mbo_benchmark.render_source_inventory_addendum --write`",
        "from `native_knowledge_delivery.classify_inventory`. Do not hand-edit: change the rules in",
        "`native_knowledge_delivery.SECTION_RULES` and re-render. The committed file is held",
        "byte-identical to the render by `tests/test_native_knowledge_delivery.py`; `--check` is the gate.",
        "",
        "## Why this addendum exists",
        "",
        "Measured in S120: of the 99 registry layers, 91 bound their evidence hash to the feed-inventory",
        "document, so the pre-call gate proved the document was unchanged and nothing about what reached",
        "Frankie. The knowledge layers must bind to the KEEP files below. Greg's rulings (2026-09-02):",
        "the proposal lineage goes in whole and its do-not-promote language is disregarded (every lesson",
        "is UNVERIFIED until he verifies it against the stream; only the refuted comes out); no historical",
        "number is a spec; nothing is dropped without discussion (D60), so every non-KEEP row below names",
        "its reason; no desktop paths (D34).",
        "",
        "## Classification vocabulary",
        "",
        "| classification | meaning |",
        "|---|---|",
    ]
    for classification in CLASSIFICATIONS:
        lines.append(f"| {classification} | {CLASSIFICATION_MEANING[classification]} |")
    lines += [
        "",
        "## Counts, derived from the table",
        "",
        "| classification | rows |",
        "|---|---|",
    ]
    for classification in CLASSIFICATIONS:
        lines.append(f"| {classification} | {counts[classification]} |")
    lines += [
        "",
        f"**{len(rows)} rows** ({with_path} with a repository path, {len(rows) - with_path} prose).",
        "Path rows absent from disk at render time: "
        + (", ".join(f"`{p}`" for p in missing) if missing else "none")
        + ".",
        "",
        "## The classification, one row per inventory bullet, in document order",
        "",
        "| # | path | section | classification | reason |",
        "|---|---|---|---|---|",
    ]
    for number, row in enumerate(rows, start=1):
        lines.append(
            f"| {number} | {_path_cell(row)} | {row.section} | {row.classification} | {_cell(row.reason)} |"
        )
    keep_py = sorted(r.path for r in rows if r.classification == KEEP and r.path and r.path.endswith(".py"))
    lines += [
        "",
        "## Notes recorded with this classification",
        "",
        "1. Section K carries one prose bullet (Step-1 seconds, populations, classifications,",
        "   crosswalks, receipts, result prefixes and reconciliation products located by the Step-1",
        "   manifests/runtime). It names no repository path, it is SEALED, and it is a row here because",
        "   a bullet the map lists is a bullet the classification must answer for.",
        f"2. `{BRAIN_PATH}` (section B) is the file the five current_brain_runtime layers bind to.",
        "   The other section-B modules are the S120-S135 runtime construction: CODE, because they",
        "   assemble the runtime that loads the brain; the brain they load is what he receives.",
        "3. Section D's two `_V3_V4_` proposal addenda are KEEP by ruling. The feed inventory's",
        "   section 3 sentence that the extra-agent carryforward is the only admissible V3-derived",
        "   material is superseded for the proposal lineage by Greg's 2026-09-02 ruling; the registry's",
        "   V3 source allowlist is extended for exactly those two files, with the ruling recorded",
        "   beside the allowlist.",
        f"4. {len(keep_py)} section-C construction/helper implementations are KEEP: they are the exact",
        "   definition of the legacy observables and structures he must recreate (feed section 8).",
        "   They bind to registry layers and are receipted; the knowledge manifest",
        "   (`native_frankie_knowledge_registry`) admits only MARKDOWN, JSON and DIRECTORY_PROOF",
        "   kinds, so they are not manifest artifacts. Recorded here, not forced.",
        "5. Section A's two inventories are KEEP as the canonical input list and bind to the",
        "   proposal-index layer as index material; every other section-A document is SUPERSEDED.",
        "6. Every KEEP path must land in at least one registry knowledge layer; the delivery receipt",
        "   refuses a KEEP path that no layer delivers and refuses any knowledge layer bound only to",
        "   the feed-inventory document.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="exit 1 if the committed addendum differs from the render")
    mode.add_argument("--write", action="store_true", help="write the render to the addendum path")
    parser.add_argument("--repo-root", default=str(REPO_ROOT))
    args = parser.parse_args(argv)
    root = Path(args.repo_root)
    rendered = render_addendum(root).encode("utf-8")
    target = root / ADDENDUM_PATH
    if args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(rendered)
        print(f"wrote {ADDENDUM_PATH} ({len(rendered)} bytes)")
        return 0
    committed = target.read_bytes() if target.is_file() else None
    if committed == rendered:
        print(f"PASS  {ADDENDUM_PATH} matches the classification render")
        return 0
    print(
        f"FAIL  {ADDENDUM_PATH} "
        + ("is absent" if committed is None else "has DRIFTED from the classification render")
        + "; run --write",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
