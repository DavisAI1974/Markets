#!/usr/bin/env python3
"""Regenerate promoted Frankie capsules and their hash-bound knowledge manifest."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys
from typing import Any

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO))

from research.kalshi.frankie_raw_mbo_benchmark.native_frankie_knowledge_registry import (  # noqa: E402
    SCHEMA,
    canonical_hash,
    load_and_validate_manifest,
)


SPEC_SCHEMA = "FRANKIE_NATIVE_RAW_MBO_KNOWLEDGE_SOURCES_V1"


class KnowledgeRefreshError(ValueError):
    """The deterministic knowledge refresh cannot be completed safely."""


def _canonical_pretty(value: Any) -> bytes:
    return (
        json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True).encode("utf-8")
        + b"\n"
    )


def _extract_section(text: str, heading: str, source_path: str) -> str:
    marker = heading + "\n"
    start = text.find(marker)
    if start < 0:
        raise KnowledgeRefreshError(f"missing capsule section in {source_path}: {heading}")
    body_start = start + len(marker)
    end = text.find("\n## ", body_start)
    body = text[body_start:] if end < 0 else text[body_start:end]
    body = body.strip()
    if not body:
        raise KnowledgeRefreshError(f"empty capsule section in {source_path}: {heading}")
    return body


def render_capsules(spec: dict[str, Any], repo_root: Path) -> dict[str, bytes]:
    rendered: dict[str, bytes] = {}
    for capsule in spec["capsules"]:
        lines = [
            f"# {capsule['title']}",
            "",
            "Generated from reviewed positive-only sources. Do not edit this file by hand;",
            "update the registered source section and run the knowledge refresh.",
            "",
        ]
        for source in capsule["sources"]:
            path = repo_root / source["path"]
            raw = path.read_bytes()
            text = raw.decode("utf-8")
            lines.extend(
                [
                    f"## {source['label']}",
                    "",
                    f"Source: `{source['path']}`",
                    f"Source SHA-256: `{hashlib.sha256(raw).hexdigest()}`",
                    "",
                    _extract_section(text, source["heading"], source["path"]),
                    "",
                ]
            )
        rendered[capsule["output_path"]] = ("\n".join(lines).rstrip() + "\n").encode(
            "utf-8"
        )
    return rendered


def build_manifest(
    spec: dict[str, Any], repo_root: Path, rendered: dict[str, bytes]
) -> dict[str, Any]:
    artifacts: list[dict[str, Any]] = []
    for row in spec["artifacts"]:
        path = row["path"]
        raw = rendered[path] if path in rendered else (repo_root / path).read_bytes()
        artifacts.append(
            {
                **row,
                "sha256": hashlib.sha256(raw).hexdigest(),
                "bytes": len(raw),
            }
        )
    manifest = {
        "schema": SCHEMA,
        "version": spec["version"],
        "artifacts": artifacts,
        "external_bindings": spec["external_bindings"],
        "profiles": spec["profiles"],
        "manifest_hash": "",
    }
    manifest["manifest_hash"] = canonical_hash(manifest, omit="manifest_hash")
    return manifest


def load_spec(path: Path) -> dict[str, Any]:
    try:
        spec = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise KnowledgeRefreshError(f"cannot load knowledge source spec: {path}") from exc
    if not isinstance(spec, dict) or spec.get("schema") != SPEC_SCHEMA:
        raise KnowledgeRefreshError("unsupported knowledge source spec")
    for key in (
        "version",
        "manifest_path",
        "capsules",
        "artifacts",
        "external_bindings",
        "profiles",
        "managed_globs",
    ):
        if key not in spec:
            raise KnowledgeRefreshError(f"knowledge source spec lacks {key}")
    return spec


def verify_managed_knowledge_inventory(spec: dict[str, Any], repo_root: Path) -> None:
    registered = {row["path"] for row in spec["artifacts"]}
    capsule_outputs = {row["output_path"] for row in spec["capsules"]}
    if not capsule_outputs <= registered:
        raise KnowledgeRefreshError("every generated capsule must be a registered artifact")
    capsule_sources = {
        source["path"] for capsule in spec["capsules"] for source in capsule["sources"]
    }
    if not capsule_sources <= registered:
        raise KnowledgeRefreshError("every promoted capsule source must be a registered artifact")
    discovered: set[str] = set()
    for pattern in spec["managed_globs"]:
        if not isinstance(pattern, str) or not pattern:
            raise KnowledgeRefreshError("managed knowledge glob must be a non-empty string")
        discovered.update(
            path.relative_to(repo_root).as_posix()
            for path in repo_root.glob(pattern)
            if path.is_file()
        )
    unregistered = sorted(discovered - registered)
    if unregistered:
        raise KnowledgeRefreshError(
            "unregistered managed knowledge files: " + ", ".join(unregistered)
        )


def refresh(spec_path: Path, repo_root: Path, *, write: bool) -> dict[str, Any]:
    spec = load_spec(spec_path)
    verify_managed_knowledge_inventory(spec, repo_root)
    rendered = render_capsules(spec, repo_root)
    manifest = build_manifest(spec, repo_root, rendered)
    expected = {**rendered, spec["manifest_path"]: _canonical_pretty(manifest)}
    stale = [
        path
        for path, raw in expected.items()
        if not (repo_root / path).is_file() or (repo_root / path).read_bytes() != raw
    ]
    if stale and not write:
        raise KnowledgeRefreshError(f"generated knowledge is stale: {', '.join(stale)}")
    if write:
        for path, raw in expected.items():
            target = repo_root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(raw)
    load_and_validate_manifest(repo_root / spec["manifest_path"], repo_root)
    return {"manifest": manifest, "updated_paths": stale}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--spec", type=Path, required=True)
    parser.add_argument("--repo-root", type=Path, required=True)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = refresh(args.spec, args.repo_root, write=args.write)
    print(
        json.dumps(
            {
                "status": "UPDATED" if args.write else "CURRENT",
                "manifest_hash": result["manifest"]["manifest_hash"],
                "updated_paths": result["updated_paths"],
            },
            sort_keys=True,
        )
    )


if __name__ == "__main__":
    main()
